using UnityEngine;

namespace StuntCar
{
    /// <summary>
    /// Entry point. Lives in the one scene, holds the material assets the editor build script
    /// generated, makes the procedural textures, and starts the race manager.
    /// </summary>
    public class GameBootstrap : MonoBehaviour
    {
        [Header("Generated by Stunt Car > Generate Project Assets")]
        public Material asphalt;
        public Material kerbRed;
        public Material kerbWhite;
        public Material concrete;
        public Material scaffold;
        public Material grass;
        public Material playerPaint;
        public Material opponentPaint;
        public Material chrome;
        public Material darkMetal;
        public Material tyre;
        public Material helmet;
        public Material boostFlame;
        public Material standSeats;
        public Material floodlight;
        public Material cable;
        public Material tailLight;
        public Material particleSmoke;
        public Material particleSpark;
        // The Blender car and its two palette liveries. Cars fall back to primitives without them.
        public GameObject carModel;
        public Material playerCarSkin;
        public Material opponentCarSkin;

        public static GameBootstrap Instance { get; private set; }
        public Material AsphaltRuntime { get; private set; }
        public PhysicsMaterial RoadPhysics { get; private set; }
        public PhysicsMaterial BodyPhysics { get; private set; }

        void Awake()
        {
            Instance = this;
            Time.fixedDeltaTime = 1f / 100f;
            Physics.defaultSolverIterations = 10;
            Application.targetFrameRate = -1;

            FillMissingMaterials();

            AsphaltRuntime = new Material(asphalt) { name = "Asphalt (runtime)" };
            AsphaltRuntime.SetTexture("_BaseMap", ProceduralTextures.Asphalt());

            var grassTex = ProceduralTextures.Grass();
            grass.SetTexture("_BaseMap", grassTex);
            grass.SetTextureScale("_BaseMap", new Vector2(400, 400));

            RoadPhysics = new PhysicsMaterial("Road") { dynamicFriction = 0.6f, staticFriction = 0.6f };
            BodyPhysics = new PhysicsMaterial("CarBody")
            {
                dynamicFriction = 0.15f,
                staticFriction = 0.15f,
                bounciness = 0.05f,
                frictionCombine = PhysicsMaterialCombine.Minimum,
            };

            Scenery.Build(this);
            gameObject.AddComponent<RaceManager>();
        }

        // Lets the scene run even if the generated assets are missing (e.g. a fresh clone opened in the editor).
        void FillMissingMaterials()
        {
            asphalt = asphalt ? asphalt : Fallback(new Color(0.25f, 0.25f, 0.27f), 0.3f);
            kerbRed = kerbRed ? kerbRed : Fallback(new Color(0.75f, 0.08f, 0.06f), 0.4f);
            kerbWhite = kerbWhite ? kerbWhite : Fallback(new Color(0.92f, 0.92f, 0.9f), 0.4f);
            concrete = concrete ? concrete : Fallback(new Color(0.55f, 0.55f, 0.52f), 0.2f);
            scaffold = scaffold ? scaffold : Fallback(new Color(0.6f, 0.62f, 0.66f), 0.55f, 0.7f);
            grass = grass ? grass : Fallback(new Color(0.36f, 0.5f, 0.24f), 0.1f);
            playerPaint = playerPaint ? playerPaint : Fallback(new Color(0.8f, 0.05f, 0.04f), 0.8f, 0.3f);
            opponentPaint = opponentPaint ? opponentPaint : Fallback(new Color(0.05f, 0.25f, 0.8f), 0.8f, 0.3f);
            chrome = chrome ? chrome : Fallback(new Color(0.85f, 0.85f, 0.88f), 0.9f, 1f);
            darkMetal = darkMetal ? darkMetal : Fallback(new Color(0.08f, 0.08f, 0.09f), 0.4f, 0.5f);
            tyre = tyre ? tyre : Fallback(new Color(0.04f, 0.04f, 0.04f), 0.2f);
            helmet = helmet ? helmet : Fallback(new Color(0.95f, 0.85f, 0.1f), 0.85f);
            boostFlame = boostFlame ? boostFlame : Fallback(new Color(1f, 0.5f, 0.1f), 0.5f);
            standSeats = standSeats ? standSeats : Fallback(new Color(0.2f, 0.3f, 0.55f), 0.3f);
            floodlight = floodlight ? floodlight : Fallback(new Color(1f, 1f, 0.9f), 0.5f);
            cable = cable ? cable : Fallback(new Color(0.1f, 0.1f, 0.1f), 0.2f);
            tailLight = tailLight ? tailLight : Fallback(new Color(0.9f, 0.05f, 0.05f), 0.6f);
            particleSmoke = particleSmoke ? particleSmoke : ParticleFallback();
            particleSpark = particleSpark ? particleSpark : ParticleFallback();
        }

        static Material ParticleFallback()
        {
            var shader = Shader.Find("Universal Render Pipeline/Particles/Unlit");
            return shader ? new Material(shader) : Fallback(Color.white, 0f);
        }

        static Material Fallback(Color c, float smoothness, float metallic = 0f)
        {
            var shader = Shader.Find("Universal Render Pipeline/Lit");
            if (shader == null) shader = Shader.Find("Standard");
            var m = new Material(shader);
            m.SetColor("_BaseColor", c);
            m.SetColor("_Color", c);
            m.SetFloat("_Smoothness", smoothness);
            m.SetFloat("_Glossiness", smoothness);
            m.SetFloat("_Metallic", metallic);
            return m;
        }
    }
}
